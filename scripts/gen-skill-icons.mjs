// Generates src/lib/skill-icons.ts from the slugs used in src/data/resume.tsx.
//
// WHY GENERATE RATHER THAN IMPORT. `simple-icons` is a 16MB package containing
// three thousand brand marks. Importing from it at runtime means trusting a
// bundler to tree-shake all but the forty we use, and being wrong about that costs
// every visitor. Generating a file with exactly the paths we asked for makes the
// question unaskable: the dependency stays in devDependencies, nothing about it
// reaches the browser, and what ships is readable in the diff.
//
// WHY NOT HAND-WRITE THE PATHS. Forty SVG path strings transcribed by hand is forty
// chances to produce a logo that is subtly wrong, and no reviewer would catch it.
// The package is the source of truth for the shapes; this just copies the subset.
//
// Re-run after adding a skill with a new icon slug. It is idempotent.
//
// Usage: node scripts/gen-skill-icons.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as si from "simple-icons";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const source = readFileSync(join(ROOT, "src/data/resume.tsx"), "utf8");
const slugs = [...new Set([...source.matchAll(/icon:\s*"([a-z0-9]+)"/g)].map((m) => m[1]))].sort();

const missing = [];
const entries = [];
for (const slug of slugs) {
  // simple-icons exports as si<PascalCase of slug>, e.g. nodedotjs -> siNodedotjs.
  const key = "si" + slug.charAt(0).toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) {
    missing.push(`${slug} (looked for ${key})`);
    continue;
  }
  entries.push(`  ${slug}: { title: ${JSON.stringify(icon.title)}, path: ${JSON.stringify(icon.path)} },`);
}

if (missing.length) {
  console.error(`No such icon in simple-icons:\n  ${missing.join("\n  ")}`);
  console.error("Fix the slug in src/data/resume.tsx, or drop `icon` so it falls back to the neutral glyph.");
  process.exit(1);
}

const out = `// GENERATED by scripts/gen-skill-icons.mjs. Do not edit by hand.
//
// The brand marks for the skills in src/data/resume.tsx, copied out of
// simple-icons so that package can stay a devDependency and nothing about it
// reaches the browser. Re-run the script after adding a slug.
//
// Paths only, no colour: every mark renders in currentColor so it sits inside the
// site's palette instead of importing ${slugs.length} unrelated brand colours into a page
// that derives every colour from one hue.

export type SkillIcon = { title: string; path: string };

export const SKILL_ICONS: Record<string, SkillIcon> = {
${entries.join("\n")}
};
`;

writeFileSync(join(ROOT, "src/lib/skill-icons.ts"), out, "utf8");
console.log(`wrote src/lib/skill-icons.ts with ${entries.length} icons`);
